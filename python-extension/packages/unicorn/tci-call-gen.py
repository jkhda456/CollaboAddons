#!/usr/bin/env python3
"""Write tcg/tci-call.inc.c: tci_call(), which calls a TCG helper as the type it has.

    tci-call-gen.py > qemu/tcg/tci-call.inc.c

The same table serves Unicorn 2's TCI (patches/0001, patches-2.0/0001: QEMU 5.0.1's tcg/tci.c) and
Unicorn 1's (patches-1.0/0001: QEMU 2.2.1's tci.c, whose helpers have at most five parameters, so
the six-parameter cases go unused there); build.sh checks each tree's copy is what this writes.

A WebAssembly host checks the type of every call through a pointer, so TCG's interpreter (tci.c)
cannot call every helper as one type with the most arguments, as QEMU's TCI does natively. A
helper's parameters and result are each a 32-bit or a 64-bit integer (pointers, softfloat's types,
target_ulong), at most MAX_OPC_PARAM_IARGS (6) parameters: 381 types, each a case here. The type
comes from the call (tcg.c, tci_call_sig): bits 0-1 the result (0 none, 1 32-bit, 2 64-bit), bits
2-4 the number of parameters, bit 5 + i the i-th parameter is 64-bit. The arguments are the call's
argument registers in order (a[]: 32-bit host registers; a 64-bit argument takes two, its low half
first, as tcg_gen_callN orders them on a little-endian host).
"""
MAX = 6
lines = [
    "/* Generated by tci-call-gen.py: tci_call(), a TCG helper called as the type it has (tci.c). */",
    "",
    "#if TCG_TARGET_REG_BITS != 32",
    "# error tci_call is for 32-bit hosts",
    "#endif",
    "",
    "#define A32(k) ((uint32_t)a[k])",
    "#define A64(k) ((uint64_t)(uint32_t)a[k] | (uint64_t)(uint32_t)a[(k) + 1] << 32)",
    "",
    "static uint64_t tci_call(tcg_target_ulong f, unsigned sig, const tcg_target_ulong *a)",
    "{",
    "    switch (sig) {",
]
rtypes = ["void", "uint32_t", "uint64_t"]
for n in range(MAX + 1):
    for mask in range(1 << n):
        params, args, k = [], [], 0
        for i in range(n):
            if mask >> i & 1:
                params.append("uint64_t")
                args.append(f"A64({k})")
                k += 2
            else:
                params.append("uint32_t")
                args.append(f"A32({k})")
                k += 1
        for r in range(3):
            sig = r | n << 2 | mask << 5
            fn = f"(({rtypes[r]} (*)({', '.join(params) or 'void'}))f)({', '.join(args)})"
            body = f"{fn}; return 0;" if r == 0 else f"return {fn};"
            lines.append(f"    case {sig:#06x}: {body}")
lines += [
    "    }",
    "    tcg_abort();",
    "}",
    "",
    "#undef A32",
    "#undef A64",
]
print("\n".join(lines))
